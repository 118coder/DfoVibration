    /// ★v24.33 确认修改连发: 移除 + 添加一次批量生效; 已占用触发键跳过
    #[test]
    fn apply_pending_changes_batches() {
        let mut cfg = AppConfig::default();
        cfg.mappings.clear(); // 出厂默认自带 Q→Q, 清空后按已知顺序构造
        cfg.mappings.push(km("S"));
        cfg.mappings.push(km("D"));

        /* 移除 S + 添加 H; D 已占用被跳过 (大小写不敏感) */
        let (removed, added) = apply_pending_changes(
            &mut cfg,
            &["s".to_string()],
            &["H".to_string(), "D".to_string()],
        );
        assert_eq!((removed, added), (1, 1));
        assert!(cfg.mappings.iter().all(|m| m.trigger_key != "S"));
        let h = cfg
            .mappings
            .iter()
            .find(|m| m.trigger_key == "H")
            .expect("H 应被添加");
        assert!(h.turbo_enabled);
        assert_eq!(h.target_keys[0], "H");

        /* 移除不存在的键: 计 0 不 panic; 无变更 */
        let (removed, added) = apply_pending_changes(&mut cfg, &["Z".to_string()], &[]);
        assert_eq!((removed, added), (0, 0));
        assert_eq!(cfg.mappings.len(), 2); // D + H
    }
