    /// 从标签串里取 key="value" 属性值 (value 解析为 f32)
    fn attr(tag: &str, key: &str) -> Option<f32> {
        let p = tag.find(key)? + key.len();
        let v = &tag[p..];
        let e = v.find('"')?;
        v[..e].parse().ok()
    }

    /// 解析 SVG 中每个 <g id="X"> 内第一个 <rect> 的几何
    fn parse_svg_geometry(svg: &str) -> Vec<(&str, f32, f32, f32, f32)> {
        let mut out = Vec::new();
        let mut rest = svg;
        while let Some(i) = rest.find("<g id=\"") {
            let after_id = &rest[i + 7..];
            let Some(id_end) = after_id.find('"') else { break };
            let id = &after_id[..id_end];
            let body_end = after_id.find("</g>").unwrap_or(after_id.len());
            let body = &after_id[..body_end];
            if let Some(r) = body.find("<rect ") {
                let tag = &body[r..];
                let tag = &tag[..tag.find('>').unwrap_or(tag.len())];
                if let (Some(x), Some(y), Some(w), Some(h)) = (
                    attr(tag, "x=\""),
                    attr(tag, " y=\""),
                    attr(tag, "width=\""),
                    attr(tag, "height=\""),
                ) {
                    out.push((id, x, y, w, h));
                }
            }
            rest = &after_id[body_end..];
        }
        out
    }

    /// ★v24.33 回归守卫: KEYS 表坐标必须与 SVG 实际 rect 几何一致。
    /// 历史 bug: 生成时浮点被格式化成 1 位有效数字 (2e+02), 102 键热区全部错位
    /// (点击 G 选中 H)。渲染把图像与热区经同一 rect 线性映射, 坐标一致 ⇒ 屏幕对齐。
    #[test]
    fn keys_table_matches_svg_geometry() {
        for (path, svg) in [
            ("dark", include_str!("../../resources/keyboard.svg")),
            ("light", include_str!("../../resources/keyboard-light.svg")),
        ] {
            let geo = parse_svg_geometry(svg);
            assert_eq!(geo.len(), KEYS.len(), "{}: SVG 键数 {} != 表条目 {}", path, geo.len(), KEYS.len());
            for k in KEYS {
                let hit = geo
                    .iter()
                    .find(|(id, ..)| id.eq_ignore_ascii_case(k.name))
                    .unwrap_or_else(|| panic!("{}: SVG 缺少键 {}", path, k.name));
                let (_, x, y, w, h) = *hit;
                assert!(
                    (k.x - x).abs() < 0.05 && (k.y - y).abs() < 0.05
                        && (k.w - w).abs() < 0.05 && (k.h - h).abs() < 0.05,
                    "{}: 键 {} 表坐标 ({},{},{},{}) != SVG ({},{},{},{})",
                    path, k.name, k.x, k.y, k.w, k.h, x, y, w, h
                );
            }
        }
    }

