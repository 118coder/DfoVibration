    /// 给控件挂上 `param_hint` 的说明 (没有登记就原样返回)。
    pub(in crate::gui) fn with_hint(resp: egui::Response, name: &str) -> egui::Response {
        let h = Self::param_hint(name);
        if h.is_empty() {
            resp
        } else {
            resp.on_hover_text(h)
        }
    }

    /// ★R2.14 非槽位震动参数滑杆的统一写路径 (旧「写 config + 写原子 + 脏标」三连
